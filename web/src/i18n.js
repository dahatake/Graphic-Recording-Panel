export function createI18n(initial = DEFAULT_LANG) {
  const dict = { ja: { ...BASE.ja }, en: { ...BASE.en } };
  let lang = LANGS.includes(initial) ? initial : DEFAULT_LANG;
  return {
    get lang() { return lang; },
    setLang(next) {
      if (!LANGS.includes(next)) return false;
      lang = next;
      return true;
    },
    t(key) { return dict[lang][key] ?? key; },
    getStrings() { return { ...dict[lang] }; },
    addStrings(strings) {
      const jaKeys = Object.keys(strings.ja || {}).sort().join('\n');
      const enKeys = Object.keys(strings.en || {}).sort().join('\n');
      if (jaKeys !== enKeys) throw new Error('i18n: ja と en のキー集合が一致しません');
      Object.assign(dict.ja, strings.ja);
      Object.assign(dict.en, strings.en);
    },
  };
}
